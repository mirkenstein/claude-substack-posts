def scrape_conversation(conv_id, max_tweets=500):
    """
    Scrape all tweets in a conversation using snscrape search.
    Returns a list of tweet dicts.
    """
    query = f"conversation_id:{conv_id} (filter:safe OR -filter:safe)"
    tweets = []
    try:
        for i, tweet in enumerate(sntwitter.TwitterSearchScraper(query).get_items()):
            if i >= max_tweets:
                break
            tweets.append({
                "tweet_id": tweet.id,
                "conversation_id": conv_id,
                "url": tweet.url,
                "username": tweet.user.username if tweet.user else None,
                "display_name": tweet.user.displayname if tweet.user else None,
                "user_id": tweet.user.id if tweet.user else None,
                "content": tweet.rawContent,
                "tweet_date": tweet.date.isoformat(),
                "reply_count": tweet.replyCount,
                "retweet_count": tweet.retweetCount,
                "like_count": tweet.likeCount,
                "quote_count": tweet.quoteCount,
                "bookmark_count": getattr(tweet, 'bookmarkCount', None),
                "views": getattr(tweet, 'viewCount', None),
                "lang": tweet.lang,
                "is_reply": tweet.inReplyToTweetId is not None,
                "in_reply_to_tweet_id": tweet.inReplyToTweetId,
                "in_reply_to_user_id": tweet.inReplyToUser.id if tweet.inReplyToUser else None,
                "in_reply_to_username": tweet.inReplyToUser.username if tweet.inReplyToUser else None,
                "quoted_tweet_id": tweet.quotedTweet.id if tweet.quotedTweet else None,
                "hashtags": [h for h in (tweet.hashtags or [])],
                "mentioned_users": [u.username for u in (tweet.mentionedUsers or [])],
                "links": [u.url for u in (tweet.links or [])],
                "media_urls": [m.fullUrl if hasattr(m, 'fullUrl') else str(m) for m in (tweet.media or [])],
                "source_label": tweet.sourceLabel,
            })
    except Exception as e:
        print(f"  ERROR scraping {conv_id}: {e}", file=sys.stderr)
    return tweets


def main():
    parser = argparse.ArgumentParser(description="Scrape Twitter conversations via snscrape")
    parser.add_argument("--limit", type=int, default=None, help="Only scrape first N conversations")
    parser.add_argument("--max-per-conv", type=int, default=500, help="Max tweets per conversation")
    parser.add_argument("--resume", action="store_true", help="Skip already-scraped conversations")
    parser.add_argument("--output", default="conversation_tweets.jsonl", help="Output JSONL file")
    parser.add_argument("--include-profile-convs", action="store_true",
                        help="Also scrape the 23 conversations from the profile-scraper file")
    parser.add_argument("--delay", type=float, default=2.0, help="Seconds between conversations")
    args = parser.parse_args()

    # Build conversation list
    all_conv_ids = list(CONVERSATION_IDS)
    if args.include_profile_convs:
        existing = set(all_conv_ids)
        for cid in PROFILE_SCRAPER_CONV_IDS:
            if cid not in existing:
                all_conv_ids.append(cid)
                existing.add(cid)

    # Load progress
    progress_file = Path("scrape_progress.json")
    done = set()
    if args.resume and progress_file.exists():
        with open(progress_file) as f:
            done = set(json.load(f).get("completed", []))
        print(f"Resuming: {len(done)} conversations already scraped")

    # Filter
    to_scrape = [c for c in all_conv_ids if c not in done]
    if args.limit:
        to_scrape = to_scrape[:args.limit]

    print(f"Scraping {len(to_scrape)} conversations (of {len(all_conv_ids)} total)")
    print(f"Output: {args.output}")
    print()

    total_tweets = 0
    with open(args.output, "a") as out:
        for i, conv_id in enumerate(to_scrape):
            print(f"[{i+1}/{len(to_scrape)}] conversation_id:{conv_id} ...", end=" ", flush=True)
            tweets = scrape_conversation(conv_id, max_tweets=args.max_per_conv)
            print(f"{len(tweets)} tweets")

            for t in tweets:
                out.write(json.dumps(t, default=str) + "\n")
            total_tweets += len(tweets)

            # Save progress
            done.add(conv_id)
            with open(progress_file, "w") as pf:
                json.dump({
                    "completed": list(done),
                    "last_updated": datetime.now().isoformat(),
                    "total_tweets_scraped": total_tweets,
                }, pf)

            if i < len(to_scrape) - 1:
                time.sleep(args.delay)

    print(f"\nDone! {total_tweets} tweets scraped from {len(to_scrape)} conversations")
    print(f"Output: {args.output}")


if __name__ == "__main__":
    main()
